-- Dong bo ho so Auth: TUYET DOI khong nhan role tu user_metadata.
create function private.sync_auth_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into public.users(id, full_name, email)
    values (new.id, left(coalesce(nullif(btrim(new.raw_user_meta_data->>'full_name'), ''),
      nullif(split_part(new.email, '@', 1), ''), 'Khách hàng'), 120), lower(new.email));
  else
    update public.users set email = lower(new.email) where id = new.id;
  end if;
  return new;
end;
$$;
create trigger phongvu_auth_insert after insert on auth.users
  for each row execute function private.sync_auth_user();
create trigger phongvu_auth_email_update after update of email on auth.users
  for each row execute function private.sync_auth_user();
-- Tai khoan email da tao truoc khi chay script cung co ho so Customer.
insert into public.users(id, full_name, email)
select id, left(coalesce(nullif(raw_user_meta_data->>'full_name', ''), split_part(email, '@', 1)), 120), lower(email)
from auth.users where email is not null;

create function private.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;
do $$
declare t text;
begin
  foreach t in array array['users','services','components','appointments','repair_orders','technician_applications'] loop
    execute format('create trigger touch_updated_at before update on public.%I for each row execute function private.touch_updated_at()', t);
  end loop;
end;
$$;

create function private.app_role() returns public.user_role
language sql stable security definer set search_path = '' as $$
  select role from public.users where id = auth.uid() and is_active;
$$;
create function private.require_role(allowed public.user_role[]) returns uuid
language plpgsql stable security definer set search_path = '' as $$
begin
  if auth.uid() is null or private.app_role() is null or not (private.app_role() = any(allowed)) then
    raise exception 'Bạn không có quyền thực hiện thao tác này.' using errcode = '42501';
  end if;
  return auth.uid();
end;
$$;
create function private.can_read_order(order_id uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.repair_orders r where r.id = order_id and (
    private.app_role() = 'Manager'
    or (private.app_role() = 'Customer' and r.customer_id = auth.uid())
    or (private.app_role() = 'Technician' and r.technician_id = auth.uid())));
$$;
create function private.can_read_appointment(appointment uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.appointments a where a.id = appointment and (
    private.app_role() = 'Manager'
    or (private.app_role() = 'Customer' and a.customer_id = auth.uid())
    or (private.app_role() = 'Technician' and exists(
      select 1 from public.repair_orders r where r.appointment_id = a.id and r.technician_id = auth.uid()))));
$$;
-- Khoa phieu truoc khi sua bao gia/trang thai, tranh hai request ghi de nhau.
create function private.editable_order(order_id uuid) returns public.repair_orders
language plpgsql security definer set search_path = '' as $$
declare r public.repair_orders;
begin
  perform private.require_role(array['Manager','Technician']::public.user_role[]);
  select * into r from public.repair_orders where id = order_id for update;
  if not found then raise exception 'Không tìm thấy phiếu sửa chữa.'; end if;
  if private.app_role() <> 'Manager' and r.technician_id is distinct from auth.uid() then
    raise exception 'Kỹ thuật viên chỉ được cập nhật việc được giao.' using errcode = '42501';
  end if;
  return r;
end;
$$;
create function private.add_event(
  appointment uuid, repair uuid, kind text, message text,
  old_status text default null, new_status text default null, visible boolean default true
) returns void language sql security definer set search_path = '' as $$
  insert into public.service_events(appointment_id,repair_order_id,actor_id,actor_name,event_type,
    message,old_status,new_status,customer_visible)
  values (appointment,repair,auth.uid(),coalesce((select full_name from public.users where id=auth.uid()),
    'Hệ thống'),kind,message,old_status,new_status,visible);
$$;

-- RPC: dat lich. Cac cot nghiep vu khong duoc INSERT/UPDATE truc tiep tu client.
create function public.create_appointment(
  p_customer_name text, p_phone_number text, p_laptop_model text,
  p_scheduled_time timestamptz, p_service_code text,
  p_issue_description text default '', p_common_issue_tags text[] default '{}',
  p_image_urls text[] default '{}', p_service_location public.service_location default 'store',
  p_service_address text default null, p_visit_notes text default null
) returns public.appointments language plpgsql security definer set search_path = '' as $$
declare actor uuid; service bigint; a public.appointments; local_time timestamp;
begin
  actor := private.require_role(array['Customer']::public.user_role[]);
  local_time := p_scheduled_time at time zone 'Asia/Ho_Chi_Minh';
  if p_scheduled_time is null or p_scheduled_time <= now() or p_scheduled_time > now()+interval '90 days'
    or local_time::time < time '08:00' or local_time::time >= time '20:00'
    or extract(minute from local_time) not in (0,30) or extract(second from local_time) <> 0 then
    raise exception 'Chọn giờ tương lai trong 90 ngày, từ 08:00 đến 19:30, cách nhau 30 phút.';
  end if;
  select id into service from public.services where code=p_service_code and is_active;
  if service is null then raise exception 'Dịch vụ không còn hoạt động.'; end if;
  if exists(select 1 from unnest(p_common_issue_tags) tag where not exists(
    select 1 from public.common_issues c where c.title=tag and c.is_active)) then
    raise exception 'Tag sự cố không hợp lệ.';
  end if;
  if exists(select 1 from unnest(p_image_urls) path where path is null
    or path not like 'users/'||actor::text||'/%' or path like '%..%') then
    raise exception 'Ảnh sự cố phải thuộc thư mục của bạn.';
  end if;
  insert into public.appointments(customer_id,customer_name,phone_number,laptop_model,service_id,
    scheduled_time,issue_description,common_issue_tags,image_urls,service_location,service_address,visit_notes)
  values(actor,btrim(p_customer_name),btrim(p_phone_number),btrim(p_laptop_model),service,
    p_scheduled_time,p_issue_description,p_common_issue_tags,p_image_urls,p_service_location,
    p_service_address,p_visit_notes) returning * into a;
  perform private.add_event(a.id,null,'appointment_created','Khách hàng đặt lịch hẹn.',null,a.status::text);
  return a;
end;
$$;

create function public.change_appointment_status(
  p_appointment_id uuid, p_status public.appointment_status, p_note text default ''
) returns public.appointments language plpgsql security definer set search_path = '' as $$
declare a public.appointments; previous public.appointment_status;
begin
  perform private.require_role(array['Customer','Manager']::public.user_role[]);
  select * into a from public.appointments where id=p_appointment_id for update;
  if not found then raise exception 'Không tìm thấy lịch hẹn.'; end if;
  if private.app_role()='Customer' and (a.customer_id is distinct from auth.uid() or p_status <> 'Cancelled') then
    raise exception 'Bạn chỉ được hủy lịch của mình.' using errcode='42501';
  end if;
  if p_status is null or not ((a.status='Pending' and p_status in ('Confirmed','Cancelled'))
    or (a.status='Confirmed' and p_status='Cancelled')) then
    raise exception 'Không thể chuyển trạng thái lịch hẹn này.';
  end if;
  if p_status='Cancelled' and length(btrim(coalesce(p_note,'')))=0 then
    raise exception 'Cần nhập lý do hủy lịch.';
  end if;
  if exists(select 1 from public.repair_orders where appointment_id=a.id) then
    raise exception 'Máy đã tiếp nhận, không thể hủy hoặc xác nhận lại lịch.';
  end if;
  previous := a.status;
  update public.appointments set status=p_status,
    cancellation_reason=case when p_status='Cancelled' then p_note else cancellation_reason end,
    confirmed_by=case when p_status='Confirmed' then auth.uid() else confirmed_by end,
    confirmed_at=case when p_status='Confirmed' then now() else confirmed_at end
  where id=a.id returning * into a;
  perform private.add_event(a.id,null,'appointment_status',coalesce(nullif(p_note,''),'Cập nhật lịch hẹn.'),previous::text,p_status::text);
  return a;
end;
$$;

create function public.receive_device(
  p_appointment_id uuid, p_serial_number text default '',
  p_initial_condition text default '', p_technician_id uuid default null
) returns public.repair_orders language plpgsql security definer set search_path = '' as $$
declare a public.appointments; r public.repair_orders; actor uuid;
begin
  actor := private.require_role(array['Manager']::public.user_role[]);
  select * into a from public.appointments where id=p_appointment_id for update;
  if not found or a.status <> 'Confirmed' then raise exception 'Chỉ tiếp nhận lịch đã xác nhận.'; end if;
  if p_technician_id is not null and not exists(select 1 from public.users
    where id=p_technician_id and role='Technician' and is_active) then
    raise exception 'Người phụ trách phải là kỹ thuật viên đang hoạt động.';
  end if;
  insert into public.repair_orders(appointment_id,customer_id,technician_id,received_by,
    laptop_info,serial_number,initial_condition)
  values(a.id,a.customer_id,p_technician_id,actor,a.laptop_model,p_serial_number,p_initial_condition)
  returning * into r;
  update public.appointments set status='Processing' where id=a.id;
  perform private.add_event(a.id,r.id,'received','Đã tiếp nhận thiết bị tại cửa hàng.','Confirmed','Received');
  return r;
end;
$$;

create function public.assign_technician(p_repair_order_id uuid,p_technician_id uuid)
returns public.repair_orders language plpgsql security definer set search_path = '' as $$
declare r public.repair_orders;
begin
  perform private.require_role(array['Manager']::public.user_role[]);
  r := private.editable_order(p_repair_order_id);
  if r.status in ('Completed','Delivered') then raise exception 'Phiếu đã hoàn tất, không đổi phân công.'; end if;
  if not exists(select 1 from public.users where id=p_technician_id and role='Technician' and is_active) then
    raise exception 'Kỹ thuật viên không hợp lệ.';
  end if;
  update public.repair_orders set technician_id=p_technician_id where id=r.id returning * into r;
  perform private.add_event(r.appointment_id,r.id,'assigned','Phân công kỹ thuật viên phụ trách.');
  return r;
end;
$$;

-- Bao gia la snapshot: doi gia danh muc sau nay khong lam doi bao gia da luu.
create function public.save_repair_quote(p_repair_order_id uuid,p_items jsonb)
returns public.repair_orders language plpgsql security definer set search_path = '' as $$
declare r public.repair_orders;
begin
  r := private.editable_order(p_repair_order_id);
  if r.status <> 'Diagnosing' then raise exception 'Chỉ sửa báo giá khi đang chẩn đoán.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then raise exception 'Báo giá phải là mảng JSON.'; end if;
  if jsonb_array_length(p_items) not between 1 and 50 then raise exception 'Báo giá cần từ 1 đến 50 hạng mục.'; end if;
  if exists(select 1 from jsonb_to_recordset(p_items) as x(component_id bigint)
    where x.component_id is not null and not exists(select 1 from public.components c
      where c.id=x.component_id and c.is_active)) then raise exception 'Linh kiện không còn hoạt động.'; end if;
  delete from public.repair_order_details where repair_order_id=r.id;
  insert into public.repair_order_details(repair_order_id,component_id,item_name,quantity,price,warranty_months,note)
  select r.id,x.component_id,btrim(x.item_name),x.quantity,x.price,coalesce(c.warranty_months,0),x.note
  from jsonb_to_recordset(p_items) as x(component_id bigint,item_name text,quantity integer,price numeric,note text)
  left join public.components c on c.id=x.component_id;
  update public.repair_orders set total_amount=(select sum(line_total) from public.repair_order_details
    where repair_order_id=r.id), quote_approved_at=null,quote_approved_by=null,quote_approval_note=null
  where id=r.id returning * into r;
  perform private.add_event(r.appointment_id,r.id,'quote_saved','Cập nhật báo giá: '||r.total_amount::text||' VND.');
  return r;
end;
$$;

create function public.change_repair_status(
  p_repair_order_id uuid,p_status public.repair_status,p_note text default ''
) returns public.repair_orders language plpgsql security definer set search_path = '' as $$
declare r public.repair_orders; previous public.repair_status;
begin
  r := private.editable_order(p_repair_order_id);
  if p_status is null or not ((r.status='Received' and p_status='Diagnosing')
    or (r.status='Diagnosing' and p_status='Pending_Approval')
    or (r.status='Repairing' and p_status='Completed')
    or (r.status='Completed' and p_status='Delivered')) then
    raise exception 'Chuyển trạng thái không hợp lệ; báo giá cần được chấp thuận trước khi sửa.';
  end if;
  if r.technician_id is null then raise exception 'Cần phân công kỹ thuật viên trước khi xử lý.'; end if;
  if p_status='Delivered' and private.app_role()<>'Manager' then
    raise exception 'Chỉ quản lý được bàn giao máy.' using errcode='42501';
  end if;
  if p_status='Pending_Approval' and not exists(select 1 from public.repair_order_details where repair_order_id=r.id) then
    raise exception 'Cần lập báo giá trước khi gửi duyệt.';
  end if;
  previous := r.status;
  update public.repair_orders set status=p_status,
    completed_at=case when p_status='Completed' then now() else completed_at end,
    delivered_at=case when p_status='Delivered' then now() else delivered_at end
  where id=r.id returning * into r;
  if p_status='Delivered' then update public.appointments set status='Completed' where id=r.appointment_id; end if;
  perform private.add_event(r.appointment_id,r.id,'repair_status',coalesce(nullif(p_note,''),'Cập nhật tiến độ sửa chữa.'),previous::text,p_status::text);
  return r;
end;
$$;

create function public.decide_repair_quote(p_repair_order_id uuid,p_approved boolean,p_note text default '')
returns public.repair_orders language plpgsql security definer set search_path = '' as $$
declare r public.repair_orders;
begin
  perform private.require_role(array['Customer','Manager']::public.user_role[]);
  select * into r from public.repair_orders where id=p_repair_order_id for update;
  if not found then raise exception 'Không tìm thấy phiếu.'; end if;
  if private.app_role()='Customer' and r.customer_id is distinct from auth.uid() then
    raise exception 'Không được duyệt báo giá của người khác.' using errcode='42501';
  end if;
  if r.status<>'Pending_Approval' or p_approved is null then raise exception 'Báo giá không ở trạng thái chờ duyệt.'; end if;
  if (private.app_role()='Manager' or not p_approved) and length(btrim(coalesce(p_note,'')))=0 then
    raise exception 'Cần ghi lý do từ chối hoặc căn cứ quản lý xác nhận thay khách.';
  end if;
  update public.repair_orders set status=case when p_approved then 'Repairing'::public.repair_status else 'Diagnosing'::public.repair_status end,
    quote_approved_by=case when p_approved then auth.uid() end,
    quote_approved_at=case when p_approved then now() end,quote_approval_note=p_note
  where id=r.id returning * into r;
  perform private.add_event(r.appointment_id,r.id,'quote_decision',
    case when p_approved then 'Chấp thuận báo giá. ' else 'Từ chối báo giá, cần kiểm tra lại. ' end||coalesce(p_note,''),
    'Pending_Approval',r.status::text);
  return r;
end;
$$;

create function public.add_repair_note(p_repair_order_id uuid,p_message text,p_customer_visible boolean default true)
returns void language plpgsql security definer set search_path = '' as $$
declare r public.repair_orders;
begin
  r := private.editable_order(p_repair_order_id);
  if r.status='Delivered' then raise exception 'Phiếu đã bàn giao, không ghi thêm nhật ký.'; end if;
  perform private.add_event(r.appointment_id,r.id,'note',p_message,null,null,p_customer_visible);
end;
$$;

create function public.submit_technician_application(p_specialization text,p_experience_years integer,p_introduction text)
returns void language plpgsql security definer set search_path = '' as $$
declare actor uuid;
begin
  actor := private.require_role(array['Customer']::public.user_role[]);
  perform 1 from public.users where id=actor for update;
  if length(btrim(coalesce(p_specialization,''))) not between 1 and 200 then raise exception 'Cần nhập chuyên môn.'; end if;
  if exists(select 1 from public.technician_applications where user_id=actor and status in ('Pending','Approved')) then
    raise exception 'Hồ sơ đã gửi hoặc được duyệt.';
  end if;
  insert into public.technician_applications(user_id,specialization,experience_years,introduction)
  values(actor,p_specialization,p_experience_years,p_introduction)
  on conflict(user_id) do update set specialization=excluded.specialization,experience_years=excluded.experience_years,
    introduction=excluded.introduction,status='Pending',submitted_at=now(),reviewed_at=null,reviewed_by=null,review_note=null;
end;
$$;
create function public.review_technician_application(p_user_id uuid,p_approved boolean,p_note text default '')
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform private.require_role(array['Manager']::public.user_role[]);
  perform 1 from public.users where id=p_user_id and role='Customer' and is_active for update;
  if not found or p_approved is null then raise exception 'Ứng viên không hợp lệ.'; end if;
  perform 1 from public.technician_applications where user_id=p_user_id and status='Pending' for update;
  if not found then raise exception 'Hồ sơ không ở trạng thái chờ duyệt.'; end if;
  if not p_approved and length(btrim(coalesce(p_note,'')))=0 then raise exception 'Cần ghi lý do từ chối.'; end if;
  update public.technician_applications set status=case when p_approved then 'Approved'::public.technician_application_status
    else 'Rejected'::public.technician_application_status end,review_note=p_note,reviewed_by=auth.uid(),reviewed_at=now()
  where user_id=p_user_id;
  if p_approved then update public.users set role='Technician' where id=p_user_id; end if;
end;
$$;

