begin;

create schema private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create type public.user_role as enum ('Customer', 'Technician', 'Manager');
create type public.appointment_status as enum
  ('Pending', 'Confirmed', 'Cancelled', 'Processing', 'Completed');
create type public.repair_status as enum
  ('Received', 'Diagnosing', 'Pending_Approval', 'Repairing', 'Completed', 'Delivered');
create type public.service_location as enum ('store', 'home');
create type public.technician_application_status as enum ('Draft', 'Pending', 'Approved', 'Rejected');

create sequence public.appointment_code_seq start 10001;
create sequence public.repair_code_seq start 10001;

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null check (length(btrim(full_name)) between 1 and 120),
  email text not null check (length(btrim(email)) between 3 and 254),
  phone_number text check (phone_number is null or phone_number ~ '^\+?[0-9][0-9 .()-]{7,19}$'),
  address text check (length(address) <= 500),
  role public.user_role not null default 'Customer',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index users_email_unique on public.users (lower(email));

create table public.services (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null check (length(btrim(name)) between 1 and 160),
  description text,
  base_price numeric(12,2) not null default 0 check (base_price >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.popular_laptops (
  id bigint generated by default as identity primary key,
  brand text not null,
  model_name text not null,
  image_url text,
  is_active boolean not null default true,
  unique (brand, model_name)
);
create table public.common_issues (
  id bigint generated by default as identity primary key,
  title text not null unique,
  category text,
  is_active boolean not null default true
);
create table public.components (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null check (length(btrim(name)) between 1 and 160),
  category text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  warranty_months integer not null default 12 check (warranty_months between 0 and 120),
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.appointments (
  id uuid primary key default gen_random_uuid(),
  code text not null unique default ('PV-' || nextval('public.appointment_code_seq')),
  customer_id uuid references public.users(id) on delete set null,
  customer_name text not null check (length(btrim(customer_name)) between 1 and 120),
  phone_number text not null check (phone_number ~ '^\+?[0-9][0-9 .()-]{7,19}$'),
  service_id bigint not null references public.services(id),
  laptop_model text not null check (length(btrim(laptop_model)) between 1 and 200),
  common_issue_tags text[] not null default '{}' check (cardinality(common_issue_tags) <= 10),
  issue_description text check (length(issue_description) <= 3000),
  image_urls text[] not null default '{}' check (cardinality(image_urls) <= 10),
  scheduled_time timestamptz not null,
  service_location public.service_location not null default 'store',
  service_address text check (length(service_address) <= 500),
  visit_notes text check (length(visit_notes) <= 1000),
  status public.appointment_status not null default 'Pending',
  cancellation_reason text,
  confirmed_by uuid references public.users(id) on delete set null,
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (service_location <> 'home' or length(btrim(service_address)) > 0),
  check (service_location <> 'home' or service_address is not null)
);
comment on column public.appointments.image_urls is
  'Object paths trong private bucket service-images; khong luu signed URL het han.';
create index appointments_customer_idx on public.appointments(customer_id);
create index appointments_schedule_idx on public.appointments(scheduled_time, status);
create index appointments_service_idx on public.appointments(service_id);
create unique index appointments_customer_slot_unique
  on public.appointments(customer_id, scheduled_time)
  where customer_id is not null and status <> 'Cancelled';

create table public.repair_orders (
  id uuid primary key default gen_random_uuid(),
  code text not null unique default ('SC-' || nextval('public.repair_code_seq')),
  appointment_id uuid unique references public.appointments(id) on delete restrict,
  customer_id uuid references public.users(id) on delete set null,
  technician_id uuid references public.users(id) on delete set null,
  received_by uuid references public.users(id) on delete set null,
  laptop_info text not null check (length(btrim(laptop_info)) between 1 and 200),
  serial_number text check (length(serial_number) <= 120),
  initial_condition text check (length(initial_condition) <= 3000),
  device_images text[] not null default '{}' check (cardinality(device_images) <= 10),
  status public.repair_status not null default 'Received',
  total_amount numeric(18,2) not null default 0 check (total_amount >= 0),
  quote_approved_by uuid references public.users(id) on delete set null,
  quote_approved_at timestamptz,
  quote_approval_note text,
  received_at timestamptz not null default now(),
  completed_at timestamptz,
  delivered_at timestamptz,
  updated_at timestamptz not null default now(),
  check (completed_at is null or completed_at >= received_at),
  check (delivered_at is null or (completed_at is not null and delivered_at >= completed_at))
);
create index repair_orders_customer_idx on public.repair_orders(customer_id);
create index repair_orders_technician_idx on public.repair_orders(technician_id, status);
create index repair_orders_status_idx on public.repair_orders(status, received_at);

create table public.repair_order_details (
  id bigint generated by default as identity primary key,
  repair_order_id uuid not null references public.repair_orders(id) on delete cascade,
  component_id bigint references public.components(id) on delete set null,
  item_name text not null check (length(btrim(item_name)) between 1 and 200),
  quantity integer not null default 1 check (quantity between 1 and 100),
  price numeric(12,2) not null check (price >= 0),
  line_total numeric(16,2) generated always as (quantity * price) stored,
  warranty_months integer not null default 0 check (warranty_months between 0 and 120),
  note text check (length(note) <= 1000),
  created_at timestamptz not null default now()
);
create index repair_order_details_order_idx on public.repair_order_details(repair_order_id);
create index repair_order_details_component_idx on public.repair_order_details(component_id);

create table public.service_events (
  id bigint generated by default as identity primary key,
  appointment_id uuid references public.appointments(id) on delete restrict,
  repair_order_id uuid references public.repair_orders(id) on delete restrict,
  actor_id uuid references public.users(id) on delete set null,
  actor_name text not null,
  event_type text not null,
  old_status text,
  new_status text,
  message text not null check (length(btrim(message)) between 1 and 3000),
  customer_visible boolean not null default true,
  created_at timestamptz not null default now(),
  check (appointment_id is not null or repair_order_id is not null)
);
create index service_events_appointment_idx on public.service_events(appointment_id, created_at);
create index service_events_order_idx on public.service_events(repair_order_id, created_at);

